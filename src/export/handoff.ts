/** Where an uploaded launch icon lands in the handoff zip */
export const ICON_FILE = 'assets/icon.png';

const THEME_ROLES: { key: keyof Theme; name: string; where: string }[] = [
  { key: 'accent', name: 'Highlight', where: 'section headings, the selected tab, input underlines/focus, checkboxes, toggles, sliders, progress bars' },
  { key: 'primary', name: 'Main buttons', where: 'fill of buttons whose style is "primary"' },
  { key: 'header', name: 'Title bar', where: 'background of each screen\'s title bar, where the platform lets the plugin color it' },
];

/** "Look and feel": the custom icon + colors, only when the designer set any */
function lookSection(p: Project, line: (s?: string) => void) {
  const t = p.theme ?? {};
  const roles = THEME_ROLES.filter((r) => t[r.key]);
  if (!p.entry.iconImage && !roles.length && !p.banner) return;
  line('## Look and feel');
  line();
  if (p.entry.iconImage) {
    line(`- **Launch icon:** \`${ICON_FILE}\` (${ICON_SIZE}×${ICON_SIZE} PNG, transparent background; also in \`ui-spec.json\` as \`entry.iconImage\`). Use it for the toolbar / menu / ribbon button on every platform, scaled to that platform's icon sizes. Don't substitute a stock icon.`);
  }
  if (roles.length) {
    line('- **Custom colors.** Use these instead of the platform\'s default accent everywhere listed. Anything not listed keeps the platform\'s own colors. Text on a colored fill uses the given text color so it stays readable.');
    line();
    line('| Role | Color | Text on it | Used for |');
    line('|---|---|---|---|');
    for (const r of roles) line(`| ${r.name} | \`${t[r.key]}\` | ${r.key === 'accent' ? 'n/a' : `\`${textOn(t[r.key]!)}\``} | ${r.where} |`);
    line();
    line('Define them once per platform (Android `res/values/colors.xml`, a WPF `ResourceDictionary`, CSS custom properties for CloudTAK/WebTAK, one Java `Color` constants class for TAKX) and reference them; don\'t repeat hex values in layouts.');
  }
  if (p.banner) bannerLines(p, line);
  line();
}

/** Zip path of a banner logo that is its own picture (the launch icon reuses ICON_FILE) */
export const bannerLogoFile = (side: 'left' | 'right') => `assets/banner-${side}.png`;

function bannerLines(p: Project, line: (s?: string) => void) {
  const b = p.banner!;
  const home = p.screens.find((s) => s.id === p.entry.openScreen);
  const logo = (side: 'left' | 'right') => {
    const l = b[side];
    if (l === undefined) return null;
    return l === 'icon' ? `the launch icon (${code(ICON_FILE)})` : `${code(bannerLogoFile(side))}`;
  };
  const [left, right] = [logo('left'), logo('right')];
  const bg = b.background ?? p.theme?.header;
  if (roles(p).length || p.entry.iconImage) line();
  line(`- **Home banner** on ${b.showOn === 'all' ? 'every pane and settings screen (not dialogs)' : `the home screen${home ? ` "${esc(home.title)}" (${code(home.id)})` : ''} only`}: one full-width strip directly under the title bar, above the screen's own content. It is not a component in the tree; build it once and reuse it.`);
  line(`  - Title: "${esc(b.title?.trim() || p.meta.name)}"${b.title?.trim() ? '' : ' (the plugin name)'}, bold, larger than body text${b.subtitle?.trim() ? `; second line underneath, smaller: "${esc(b.subtitle.trim())}"` : ''}. Text is ${b.align === 'center' ? 'centered between the logos' : 'left-aligned (after the left logo)'}.`);
  line(`  - Logos (about 44 dp/px tall, keep the aspect ratio): ${[left && `left: ${left}`, right && `right: ${right}`].filter(Boolean).join('; ') || 'none, text only'}.`);
  line(`  - Background: ${bg ? `${code(bg)}, text ${code(textOn(bg))}` : "the platform's header/section color"}; a 2 px line in the highlight color along the bottom.`);
}

const roles = (p: Project) => THEME_ROLES.filter((r) => p.theme?.[r.key]);

function typeWords(f: StateField): string {
  switch (f.type) {
    case 'enum': return 'choice';
    case 'list': return 'list of records';
    case 'point': return 'map location';
    case 'contact': return 'TAK contact';
    case 'boolean': return 'yes/no';
    case 'datetime': return 'date/time';
    default: return f.type;
  }
}

function fieldDetails(f: StateField, path: string[], line: (s?: string) => void) {
  const name = [...path, f.key].join('.');
  if (f.type === 'enum' && f.options?.length) {
    line(`**${code(name)} options:** ${f.options.map((o) => `${code(o.value)} "${o.label}"${o.color ? ` (${o.color})` : ''}`).join(', ')}`);
    line();
  }
  if (f.type === 'list' && f.itemFields?.length) {
    line(`**${code(name)}: each item has:** ${f.itemFields.map((i) => `${code(i.key)} (${typeWords(i)})`).join(', ')}`);
    line();
    for (const i of f.itemFields) fieldDetails(i, [...path, f.key], line);
  }
}

function kindWords(a: Action): string {
  return ({ 'cot-send': 'send a CoT event', http: 'call a web API', 'map-pick': 'pick a point on the map', navigate: 'open a screen', 'state-set': 'change a data field', notify: 'show the user a message', custom: 'custom behavior' } as const)[a.kind];
}

function triggerMap(p: Project): Map<string, string[]> {
  const m = new Map<string, string[]>();
  for (const { node } of walkWithAncestors(p)) {
    const label = componentSpec(node.kind, node.type)?.label ?? node.type;
    for (const [ev, id] of Object.entries(node.on ?? {})) m.set(id, [...(m.get(id) ?? []), `${label} ${code('#' + node.id)} (${ev})`]);
  }
  return m;
}

/** The visible text of a node, for the outline */
function textOf(n: Node): string | undefined {
  const t = n.props.text ?? n.props.title ?? n.props.label;
  return typeof t === 'string' && t ? t : undefined;
}

function describeProps(n: Node, spec: ComponentSpec): string[] {
  const out: string[] = [];
  for (const [k, v] of Object.entries(n.props)) {
    if (['text', 'title', 'label'].includes(k)) continue;
    const ps = spec.props[k];
    const name = ps?.label.toLowerCase() ?? k;
    if (typeof v === 'boolean') { if (v) out.push(name); }
    else if (Array.isArray(v)) out.push(`${name}: ${v.map((x) => `"${x}"`).join(', ')}`);
    else out.push(`${name}: ${typeof v === 'string' ? `"${v}"` : v}`);
  }
  return out;
}

function outline(p: Project, n: Node, depth: number, line: (s?: string) => void, isRoot = false) {
  const spec = componentSpec(n.kind, n.type);
  const pad = '  '.repeat(depth);
  const label = spec?.label ?? n.type;
  const parts: string[] = [`**${label}**`];
  const text = textOf(n);
  if (text) parts.push(`"${text}"`);
  parts.push(code('#' + n.id));
  if (n.bind) parts.push(`connected to ${code(n.bind)}`);
  for (const [ev, a] of Object.entries(n.on ?? {})) parts.push(`on ${ev} → action ${code(a)}`);
  if (n.visibleWhen) {
    const v = n.visibleWhen;
    parts.push(`only shown when ${code(v.key)} ${VIS_WORDS[v.op]}${v.value !== undefined ? ` ${code(String(v.value))}` : ''}`);
  }
  if (spec) {
    const extra = describeProps(n, spec);
    if (extra.length) parts.push(`(${extra.join('; ')})`);
  }
  const hidden = Object.entries(n.targetOverrides ?? {}).filter(([, o]) => o?.hidden).map(([t]) => TARGET_NAMES[t as Target]);
  if (hidden.length) parts.push(`**not shown on ${hidden.join(', ')}**`);
  for (const [t, o] of Object.entries(n.targetOverrides ?? {})) {
    if (o?.props && Object.keys(o.props).length) parts.push(`on ${TARGET_NAMES[t as Target]}: ${Object.entries(o.props).map(([k, v]) => `${k} = ${JSON.stringify(v)}`).join(', ')}`);
  }
  if (isRoot) parts[0] = `**${label}** (screen root)`;
  line(`${pad}- ${parts.join(' · ')}`);

  if (n.kind !== 'container') return;
  if (n.type === 'list') line(`${pad}  - _Row template: repeated once per item in ${code(n.bind ?? '?')}; \`$item.x\` means that item's field x._`);
  if (n.type === 'tabs') line(`${pad}  - _Each child below is one tab; its title is the tab label._`);
  for (const c of n.children) outline(p, c, depth + 1, line);
}

/** Components a target supports only approximately or not at all, with where they're used */
function caveatsFor(p: Project, t: Target): string[] {
  const seen = new Map<ComponentSpec, string[]>();
  for (const { node } of walkWithAncestors(p)) {
    if (node.targetOverrides?.[t]?.hidden) continue;
    const spec = componentSpec(node.kind, node.type);
    if (!spec) continue;
    const s = spec.support[t];
    if (s === 'approx' || s === 'none') seen.set(spec, [...(seen.get(spec) ?? []), code('#' + node.id)]);
  }
  return [...seen].map(([spec, ids]) => {
    const how = spec.support[t] === 'none' ? 'no native equivalent: propose an alternative before building' : 'no stock widget: compose it from native pieces so it looks and behaves as described';
    return `**${spec.label}** (${ids.join(', ')}): ${how}.`;
  });
}

function checklist(p: Project): string[] {
  const items: string[] = [];
  for (const t of p.meta.targets) items.push(`Builds and loads in ${TARGET_NAMES[t]}; the launch button "${p.entry.label}" opens ${code(p.entry.openScreen)}.`);
  for (const s of p.screens) {
    let n = 0;
    for (const { node } of walkWithAncestors({ ...p, screens: [s] })) if (node.kind === 'element') n++;
    items.push(`Screen ${code(s.id)} ("${s.title}") shows all ${n} components in the documented order and grouping.`);
  }
  for (const a of p.actions) items.push(`Action ${code(a.id)} does what its description says, from every trigger listed.`);
  const remembered = p.state.filter((f) => f.persisted).map((f) => code(f.key));
  if (remembered.length) items.push(`Remembered fields survive a restart: ${remembered.join(', ')}.`);
  const conditional: string[] = [];
  for (const { node, ancestors } of walkWithAncestors(p)) {
    if (node.visibleWhen && resolveKey(p, ancestors, node.visibleWhen.key)) conditional.push(code('#' + node.id));
  }
  if (conditional.length) items.push(`Show/hide rules work for ${conditional.join(', ')}: toggle the condition both ways.`);
  const lists = p.state.filter((f) => f.type === 'list').map((f) => code(f.key));
  if (lists.length) items.push(`Lists render empty, one-item and many-item states correctly: ${lists.join(', ')}.`);
  const secretish = p.state.filter((f) => /key|token|secret|password/i.test(f.key + ' ' + (f.label ?? ''))).map((f) => code(f.key));
  if (secretish.length) items.push(`Secrets (${secretish.join(', ')}) are never logged, never committed and never bundled in a build.`);
  items.push('No features, screens or settings were added beyond this document (suggestions listed separately).');
  return items;
}
