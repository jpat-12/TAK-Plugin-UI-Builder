// HANDOFF.md and the paste-into-Claude-Code prompt: pure functions of a Project (PLAN.md §3).
// Written for the CODING AGENT as reader: it states what to build, maps every spec concept
// to the target platform, and ends with a checklist the agent can verify against. Output is
// deterministic (generatedAt is passed in) so it can be snapshot-tested.

import { componentSpec, type ComponentSpec } from '../spec/catalog';
import { walkWithAncestors, resolveKey } from '../spec/tree';
import { textOn } from '../spec/color';
import { ICON_SIZE, SPEC_VERSION, type Theme, type Action, type Node, type Project, type StateField, type Target } from '../spec/types';
import { TARGET_NAMES } from '../spec/validate';
import { PLATFORM_GUIDES } from './platforms';

/** label: which tab the image shows, for tabbed screens */
export interface MockupRef { target: Target; screen: string; file: string; label?: string }

export interface HandoffOptions {
  /** ISO date string; injected so output is reproducible */
  generatedAt: string;
  mockups?: MockupRef[];
  /** targets whose generated code ships in scaffold/<target>/ (Phase 3) */
  scaffold?: Target[];
}

const esc = (s: string) => s.replace(/\|/g, '\\|').replace(/\n/g, ' ');
const code = (s: string) => '`' + s + '`';
const VIS_WORDS = { truthy: 'is on / set', falsy: 'is off / empty', eq: 'equals', neq: 'is not' } as const;

export function buildHandoff(p: Project, opts: HandoffOptions): string {
  const out: string[] = [];
  const line = (s = '') => out.push(s);
  const targets = p.meta.targets;
  const targetList = targets.map((t) => TARGET_NAMES[t]).join(', ');

  // ---- header ----
  line(`# ${p.meta.name || 'Untitled plugin'}: build handoff`);
  line();
  line(`> Generated by TAK Plugin UI Builder on ${opts.generatedAt} · spec ${SPEC_VERSION} · plugin v${p.meta.version}`);
  line();
  if (p.meta.description) { line(p.meta.description); line(); }
  line('| | |');
  line('|---|---|');
  line(`| Package id | ${code(p.meta.packageId)} |`);
  line(`| Build for | ${targetList} |`);
  const iconWords = p.entry.iconImage ? ` (icon: ${code(ICON_FILE)}${p.entry.icon ? `, ${esc(p.entry.icon)}` : ''})` : p.entry.icon ? ` (icon idea: ${esc(p.entry.icon)})` : '';
  line(`| Launch button | "${esc(p.entry.label)}"${iconWords} → opens ${code(p.entry.openScreen)} |`);
  line(`| Screens | ${p.screens.length} · Data fields ${p.state.length} · Actions ${p.actions.length} |`);
  line();

  // ---- instructions for the agent ----
  line('## Instructions for the coding agent');
  line();
  line('You are implementing a TAK plugin whose UI was designed visually. This file plus `ui-spec.json` (same folder) are the source of truth.');
  line();
  line('1. **Build exactly what is described.** Every screen, component, data field and action below must exist. Don\'t add features, screens or settings that aren\'t here; suggest them separately instead.');
  line('2. **Layout is structural, not pixel-exact.** Follow the nesting order and grouping. The mockups show the intended look, but use each platform\'s native widgets and spacing.');
  line('3. **Actions are described in plain English** (the "What it does" text). Implement that behavior. If an intent is ambiguous or needs information you don\'t have (a server URL, a CoT type), stop and ask instead of guessing.');
  line('4. **Keep the ids.** Use the `#ids` below (camelCased where the language needs it) as view ids, component refs or element ids, so anyone can trace code back to the design.');
  line('5. **Data fields are the plugin\'s state.** Components marked "connected to" read and write that field. Fields marked *remembered* must survive a restart.');
  line(`6. **Build for each target:** ${targetList}. Shared logic should live in one place per platform, not be copied per screen.`);
  line('7. Finish by working through the **Acceptance checklist** at the end and reporting which items you verified and how.');
  if (opts.scaffold?.length) line('8. **Start from the generated scaffold** (below) instead of writing layouts by hand. It already compiles; your job is wiring it into the plugin and implementing the actions.');
  line();
  if (opts.scaffold?.length) {
    line('## Generated scaffold');
    line();
    line("Layouts, data fields and action stubs are generated from the design and checked by the builder's tests (each platform's real compiler or runtime). Each folder has a `SCAFFOLD.md` with wiring steps.");
    line();
    const what: Record<string, string> = {
      atak: 'Android layout XML + `PluginState` / `Actions` / one `*Views` class per screen (aapt2 + javac verified)',
      cloudtak: 'Vue 3 panels + typed `state.ts` / `actions.ts` (vue-tsc --strict verified)',
      wintak: 'WPF XAML views + C# 7.3 `PluginViewModel` (dotnet build verified)',
      webtak: 'DOM panels + `state.js` / `actions.js` / `styles.js` (executed in a browser DOM)',
      takx: 'Swing panels + `PluginState` / `Actions` / an `@AppPlugin` class (javac --release 17 verified against the 5.8.0 API)',
    };
    for (const t of opts.scaffold) line(`- \`scaffold/${t}/\`: ${what[t] ?? 'generated code'}`);
    line();
  }
  if (p.handoff?.notes?.trim()) {
    line('### Notes from the designer');
    line();
    for (const l of p.handoff.notes.trim().split('\n')) line(`> ${l}`);
    line();
  }

  // ---- platforms ----
  lookSection(p, line);

  line('## Platforms');
  line();
  for (const t of targets) {
    const g = PLATFORM_GUIDES[t];
    line(`### ${g.name}`);
    line();
    const starter = p.handoff?.starters?.[t]?.trim();
    if (starter) line(`**Start from:** ${code(starter)}. Copy its build setup and conventions instead of starting from a blank SDK project.`);
    else line('**Start from:** the official SDK / plugin template for this platform (no starter repo was given).');
    line();
    line(g.stack);
    line();
    for (const m of g.mapping) line(`- **${m.concept}:** ${m.how}`);
    for (const r of g.rules) line(`- ${r}`);
    const caveats = caveatsFor(p, t);
    if (caveats.length) {
      line();
      line(`Components that need extra care on ${TARGET_NAMES[t]}:`);
      for (const c of caveats) line(`- ${c}`);
    }
    line();
  }

  // ---- data model ----
  line('## Data fields');
  line();
  if (!p.state.length) line('_None. This plugin keeps no state._');
  else {
    line('| Field | Type | Label | Starts as | Remembered | Notes |');
    line('|---|---|---|---|---|---|');
    for (const f of p.state) {
      line(`| ${code(f.key)} | ${typeWords(f)} | ${esc(f.label ?? '')} | ${f.default === undefined || f.default === '' ? '—' : code(String(f.default))} | ${f.persisted ? 'yes' : ''} | ${esc(f.description ?? '')} |`);
    }
    line();
    for (const f of p.state) fieldDetails(f, [], line);
  }
  line();

  // ---- actions ----
  line('## Actions');
  line();
  const triggers = triggerMap(p);
  if (!p.actions.length) line('_None._');
  for (const a of p.actions) {
    line(`### ${code(a.id)}: ${a.label}`);
    line();
    line(`- **Kind:** ${kindWords(a)}`);
    for (const [k, v] of Object.entries(a.params ?? {})) line(`- **${k}:** ${code(v)}`);
    const by = triggers.get(a.id) ?? [];
    line(`- **Triggered by:** ${by.length ? by.join(', ') : '_nothing yet_'}`);
    line(`- **What it does:** ${a.intent.trim() || '_(no description, so ask the designer)_'}`);
    line();
  }

  // ---- screens ----
  line('## Screens');
  line();
  for (const s of p.screens) {
    const surface = s.surface === 'pane' ? 'side pane' : s.surface === 'dialog' ? 'dialog (pop-up)' : 'settings page';
    line(`### ${s.title} ${code('#' + s.id)}`);
    line();
    line(`Shown as a **${surface}**${p.entry.openScreen === s.id ? '. **The launch button opens this screen.**' : '.'}`);
    line();
    const shots = (opts.mockups ?? []).filter((m) => m.screen === s.id);
    for (const m of shots) line(`![${s.title}${m.label ? ` › ${m.label}` : ''} on ${TARGET_NAMES[m.target]}](${m.file})`);
    if (shots.length) line();
    outline(p, s.root, 0, line, true);
    line();
  }

  // ---- acceptance ----
  line('## Acceptance checklist');
  line();
  for (const item of checklist(p)) line(`- [ ] ${item}`);
  line();
  return out.join('\n');
}

/** Prompt for Claude Code. 'zip' points at the unzipped folder; 'inline' embeds everything. */
/** The spec minus uploaded pictures' base64 (too big to paste; the zip carries the PNGs) */
function withoutImages(p: Project): Project {
  const out: Project = { ...p };
  if (p.entry.iconImage) {
    const { iconImage: _drop, ...entry } = p.entry;
    out.entry = entry;
  }
  if (p.banner) {
    const banner = { ...p.banner };
    // a logo with its own picture is described in HANDOFF.md (assets/banner-<side>.png)
    for (const side of ['left', 'right'] as const) if (banner[side] && banner[side] !== 'icon') delete banner[side];
    out.banner = banner;
  }
  return out;
}
const hasImages = (p: Project) => !!p.entry.iconImage || [p.banner?.left, p.banner?.right].some((l) => l && l !== 'icon');

export function buildPrompt(p: Project, mode: 'zip' | 'inline', handoffMd = ''): string {
  const targets = p.meta.targets.map((t) => TARGET_NAMES[t]).join(', ');
  const head = `Build the TAK plugin "${p.meta.name}" (${p.meta.packageId}) for ${targets}.`;
  if (mode === 'zip') {
    return [
      head,
      '',
      'The design is in this folder: read HANDOFF.md first (instructions, platform notes, data fields, actions, screens and an acceptance checklist), use ui-spec.json as the machine-readable source of truth, and look at mockups/ for the intended layout. If there is a scaffold/ folder, start from that generated code (see each SCAFFOLD.md).',
      '',
      'Before writing code: summarize the plan per platform and list any questions about unclear actions. Then implement, and finish by going through the acceptance checklist.',
      '',
    ].join('\n');
  }
  return [
    head,
    '',
    'Below are the design handoff (HANDOFF.md) and the machine-readable spec (ui-spec.json). Save both into the project as docs/HANDOFF.md and docs/ui-spec.json, summarize your plan per platform and list any questions about unclear actions before writing code, then implement and finish with the acceptance checklist.',
    '',
    ...(hasImages(p) ? [`The pictures (launch icon / banner logos, under assets/) are too big to paste here. Ask me for them before you build the launch button or banner; they come in the builder's zip export.`, ''] : []),
    '<HANDOFF.md>',
    handoffMd.trim(),
    '</HANDOFF.md>',
    '',
    '<ui-spec.json>',
    JSON.stringify(withoutImages(p), null, 2),
    '</ui-spec.json>',
    '',
  ].join('\n');
}

