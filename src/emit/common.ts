// Shared helpers for the code emitters (PLAN.md Phase 3). Emitters are pure functions
// Project → { path: contents }. They read the catalog for meaning and spec/overrides for
// per-target views, and must be deterministic (snapshot-tested, compiled in tests).

import type { Project, StateField } from '../spec/types';

export type FileMap = Record<string, string>;

/** "me-send" → ["me", "send"]; "myStatus" → ["my", "status"] */
export function words(s: string): string[] {
  return s.replace(/([a-z0-9])([A-Z])/g, '$1 $2').split(/[^a-zA-Z0-9]+/).filter(Boolean).map((w) => w.toLowerCase());
}
export const camel = (s: string) => words(s).map((w, i) => (i ? w[0]!.toUpperCase() + w.slice(1) : w)).join('');
export const pascal = (s: string) => words(s).map((w) => w[0]!.toUpperCase() + w.slice(1)).join('');
export const snake = (s: string) => words(s).join('_');
export const upperSnake = (s: string) => snake(s).toUpperCase();

/** Last packageId segment, used to prefix generated resources so they can't collide with the host template's */
export const shortName = (p: Project) => p.meta.packageId.split('.').pop()!.replace(/[^a-z0-9]/g, '');

const JAVA_RESERVED = new Set(('abstract assert boolean break byte case catch char class const continue default do double else enum extends final '
  + 'finally float for goto if implements import instanceof int interface long native new package private protected public return short static '
  + 'strictfp super switch synchronized this throw throws transient try void volatile while true false null var record yield').split(' '));
const CS_RESERVED = new Set(('abstract as base bool break byte case catch char checked class const continue decimal default delegate do double else '
  + 'enum event explicit extern false finally fixed float for foreach goto if implicit in int interface internal is lock long namespace new null '
  + 'object operator out override params private protected public readonly ref return sbyte sealed short sizeof stackalloc static string struct '
  + 'switch this throw true try typeof uint ulong unchecked unsafe ushort using virtual void volatile while').split(' '));
const JS_RESERVED = new Set(('break case catch class const continue debugger default delete do else enum export extends false finally for function '
  + 'if import in instanceof new null return super switch this throw true try typeof var void while with yield let static await').split(' '));

export const javaIdent = (s: string) => (JAVA_RESERVED.has(s) ? `${s}_` : s);
export const csIdent = (s: string) => (CS_RESERVED.has(s) ? `@${s}` : s);
export const jsIdent = (s: string) => (JS_RESERVED.has(s) ? `${s}_` : s);

export function xmlEsc(s: string): string {
  return s.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');
}
/** Android string resources additionally need \' \" and a leading @ or ? escaped */
export function androidStr(s: string): string {
  return xmlEsc(s).replace(/\\/g, '\\\\').replace(/'/g, "\\'").replace(/&quot;/g, '\\"').replace(/^([@?])/, '\\$1').replace(/\n/g, '\\n');
}
/** A Java/C#/JS double-quoted string literal */
export const strLit = (s: string) => JSON.stringify(s);

/** Comment-safe one-liner (no comment terminators, no newlines) */
export const commentSafe = (s: string) => s.replace(/\*\//g, '* /').replace(/-->/g, '- ->').replace(/\s*\n\s*/g, ' ');

export const HEADER_NOTE = 'Generated by TAK Plugin UI Builder from ui-spec.json. Scaffold: edit freely, but regenerating overwrites.';

/** Fields of a list's items, or [] */
export const itemFieldsOf = (f: StateField | undefined) => (f?.type === 'list' ? f.itemFields ?? [] : []);
